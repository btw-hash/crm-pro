import type { PasswordHasher } from "@/application/ports/password-hasher";
import type { SessionRepository } from "@/application/ports/session-repository";
import type { UserRepository } from "@/application/ports/user-repository";

export class InvalidCredentialsError extends Error {
  constructor() {
    // Intentionally not revealing which part is wrong (username or password).
    super("Invalid username or password");
    this.name = "InvalidCredentialsError";
  }
}

export interface LoginInput {
  readonly username: string;
  readonly password: string;
}

export type Login = (input: LoginInput) => Promise<{ token: string }>;

/** Verifies the account and creates a session. The token/expiry is generated by SessionRepository. */
export function makeLogin(deps: {
  users: UserRepository;
  sessions: SessionRepository;
  hasher: PasswordHasher;
}): Login {
  return async function login({ username, password }) {
    const user = await deps.users.findByUsername(username.trim().toLowerCase());
    if (!user || !deps.hasher.verify(password, user.passwordHash)) {
      throw new InvalidCredentialsError();
    }
    const session = await deps.sessions.create(user.id);
    return { token: session.token };
  };
}
